/// THE MARK, AS ARTWORK — the real logo, not an impression of it.
///
/// An earlier version of this file drew `un` from Canvas paths. It was a guess:
/// nobody had opened the actual logo, and it showed — wrong stroke weight, the
/// wrong bowl on the `u`, and the signal arcs wrapped around the `n`'s shoulder
/// instead of standing off its top right. Close enough to look deliberate and
/// wrong enough to be somebody else's brand.
///
/// This is the mark itself, lifted from the app icon: cropped to its bounding
/// box, un-composited from the icon's black ground into straight alpha, and
/// scaled to 126x78 (six times the 13pt the bar renders it at, so it stays
/// crisp on any display).
///
